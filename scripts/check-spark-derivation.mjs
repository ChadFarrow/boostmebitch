// Pins the two key derivations whose silent change is unrecoverable for users.
//
// Usage:
//   npm run check:spark
//
// Run it after ANY edit to lib/v4v/spark-derive.ts or lib/nostr/backup-crypto.ts.
// This is not a unit test in search of coverage — the repo has no test runner
// and doesn't want one. It exists because these two functions share a property
// almost nothing else in the codebase has: changing them breaks nothing
// visible, passes typecheck and lint, and costs real users real access with no
// error message anywhere.
//
//   sparkMnemonicFromKey  — moves every derived Spark wallet. Users whose funds
//                           live in one land on a different, empty wallet.
//   deriveBackupKey       — locks every user out of their Drive backup blob.
//                           There is no reset path; the PIN is the only secret.
//
// It also pins the constants those two are built from, because they are now
// published as docs/google-key-backup-spec.md for other apps to implement. A
// derivation can also break by having a *name* tidied rather than a formula
// changed, and that edit looks completely harmless in review.
//
// `--experimental-strip-types` lets this .mjs import the real .ts modules, so
// the pin executes production code rather than a copy of it. A copy would pass
// green while the shipping label changed, which is the exact failure being
// guarded against. The vectors below were generated BY the shipping code and
// cross-checked against the pre-extraction implementation — never hand-written.
//
// Two stderr warnings are expected and harmless: ExperimentalWarning (type
// stripping) and the "Reparsing as ES module" notice. Do NOT silence the second
// by adding "type": "module" to package.json — that reinterprets
// postcss.config.js / tailwind.config.js and can break the build.

import { sparkMnemonicFromKey } from '../lib/v4v/spark-derive.ts';
import {
  deriveBackupKey,
  encryptNsec,
  decryptNsec,
  ARGON2_MEMORY_KIB,
  ARGON2_PARALLELISM,
  ARGON2_TIME_COST,
  BACKUP_KEY_BYTES,
  BACKUP_LABEL,
  PIN_MAX_LENGTH,
  PIN_MIN_LENGTH,
} from '../lib/nostr/backup-crypto.ts';
import { BACKUP_FILENAME_PREFIX } from '../lib/nostr/drive-backup.ts';
import { validateMnemonic } from '@scure/bip39';
import { wordlist } from '@scure/bip39/wordlists/english.js';
import { bytesToHex } from '@noble/hashes/utils.js';

let failures = 0;

function check(label, actual, expected) {
  if (actual === expected) {
    console.log(`  ok   ${label}`);
    return true;
  }
  console.error(`  FAIL ${label}\n       expected: ${expected}\n       actual:   ${actual}`);
  failures++;
  return false;
}

// --- Spark wallet derivation -----------------------------------------------
// HMAC-SHA256('bmb-spark-wallet', sk) truncated to 16 bytes -> 12 BIP-39 words.

const SPARK_VECTORS = [
  {
    sk: '00'.repeat(31) + '01',
    mnemonic: 'million pioneer clever scan region alert gasp excite ask unknown chapter spatial',
  },
  {
    sk: '11'.repeat(32),
    mnemonic: 'rather jeans custom always leopard fly vintage naive apology section during dinner',
  },
  {
    sk: 'deadbeef'.repeat(8),
    mnemonic: 'crane lumber rubber hold lion boring culture hunt story corn audit fan',
  },
];

console.log('sparkMnemonicFromKey — frozen vectors');
for (const { sk, mnemonic } of SPARK_VECTORS) {
  const actual = await sparkMnemonicFromKey(sk);
  if (check(`${sk.slice(0, 16)}…`, actual, mnemonic)) {
    // A matching vector that isn't a usable BIP-39 phrase would mean we froze a
    // broken value, so assert the shape independently of the comparison.
    check(`${sk.slice(0, 16)}… is 12 words`, actual.split(' ').length, 12);
    check(`${sk.slice(0, 16)}… valid BIP-39`, validateMnemonic(actual, wordlist), true);
  }
}

// The input guard is part of the contract: a caller passing a malformed key
// must get a throw, not a wallet derived from garbage.
console.log('sparkMnemonicFromKey — input guard');
for (const [label, bad] of [['non-hex', 'zz'.repeat(32)], ['63 chars', '0'.repeat(63)]]) {
  let threw = false;
  try {
    await sparkMnemonicFromKey(bad);
  } catch {
    threw = true;
  }
  check(`rejects ${label}`, threw, true);
}

// --- Google backup key derivation ------------------------------------------
// Argon2id(pin, salt = HMAC-SHA256('bmb-google-backup', sub)), m=32MiB t=3 p=1.
// Each call is deliberately expensive (~0.7s); two vectors is enough.

const BACKUP_VECTORS = [
  {
    sub: '110000000000000000000',
    pin: '123456',
    key: '47adc18b00a85a0112d6cf8180fb822c23dae56d7c1b2c0eef5dbd2074707011',
  },
  {
    sub: 'test-google-sub',
    pin: '87654321',
    key: 'bb3aae52328a2f96eb12d2bfef55f31b22fecd2669d5c086e72bbab90ba6277b',
  },
];

console.log('deriveBackupKey — frozen vectors');
for (const { sub, pin, key } of BACKUP_VECTORS) {
  check(`${JSON.stringify(sub)} + ${pin}`, bytesToHex(await deriveBackupKey(sub, pin)), key);
}

// NIP-44 uses a random nonce, so the ciphertext isn't pinnable — but the
// round-trip is, and a wrong key must fail closed via the MAC rather than
// returning garbage.
console.log('encryptNsec / decryptNsec — round-trip');
{
  const sk = 'ab'.repeat(32);
  const key = await deriveBackupKey(BACKUP_VECTORS[0].sub, BACKUP_VECTORS[0].pin);
  const wrong = await deriveBackupKey(BACKUP_VECTORS[1].sub, BACKUP_VECTORS[1].pin);
  check('decrypts under the right key', decryptNsec(encryptNsec(sk, key), key), sk);

  let threw = false;
  try {
    decryptNsec(encryptNsec(sk, key), wrong);
  } catch {
    threw = true;
  }
  check('throws under the wrong key', threw, true);
}

// --- Published wire constants ----------------------------------------------
// These are quoted verbatim by docs/google-key-backup-spec.md, which exists so
// other apps can restore the same blobs. A vector above catches a derivation
// that MOVED; these catch the rename that looks like tidying — dropping a `bmb-`
// prefix, "rounding" 32 MiB, tightening the PIN maximum — each of which changes
// the format while every derivation still agrees with itself.

console.log('published wire constants — frozen values');
for (const [label, actual, expected] of [
  ['BACKUP_LABEL', BACKUP_LABEL, 'bmb-google-backup'],
  ['BACKUP_FILENAME_PREFIX', BACKUP_FILENAME_PREFIX, 'bmb_bk_'],
  ['ARGON2_MEMORY_KIB', ARGON2_MEMORY_KIB, 32768],
  ['ARGON2_TIME_COST', ARGON2_TIME_COST, 3],
  ['ARGON2_PARALLELISM', ARGON2_PARALLELISM, 1],
  ['BACKUP_KEY_BYTES', BACKUP_KEY_BYTES, 32],
  ['PIN_MIN_LENGTH', PIN_MIN_LENGTH, 6],
  ['PIN_MAX_LENGTH', PIN_MAX_LENGTH, 8],
]) {
  check(label, actual, expected);
}

if (failures > 0) {
  console.error(
    `\n${failures} check(s) FAILED — A DERIVATION OR A PUBLISHED CONSTANT CHANGED.\n\n` +
      'If sparkMnemonicFromKey moved: every user with funds in a derived Spark\n' +
      'wallet has just lost access to them from the same nsec. They land on a\n' +
      'different, empty wallet with no error.\n\n' +
      'If deriveBackupKey moved: every user is locked out of their Drive backup.\n' +
      'The PIN is the only secret and there is no reset path.\n\n' +
      'If a wire constant moved: the same, plus every OTHER app implementing\n' +
      'docs/google-key-backup-spec.md is now incompatible with this one. Those\n' +
      'names are not app-local settings — the `bmb-` prefix is historical and\n' +
      'renaming it is a breaking change, not a cleanup.\n\n' +
      'Do not update the vectors to match. Revert the change, or version the\n' +
      'derivation (a NEW label, try v1 first on restore) and migrate deliberately.\n' +
      'See the ⚠️ block in lib/v4v/spark-derive.ts and §8 of the spec.',
  );
  process.exitCode = 1;
} else {
  console.log('\nAll derivation checks passed.');
}
