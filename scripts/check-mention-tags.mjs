// Pins which people a boost note TAGS versus merely names in its body.
//
// Usage:
//   npm run check:mentions
//
// Run it after ANY edit to lib/nostr/mention-tags.ts, and after any change to
// how buildBoostNoteTemplate decides `selfSigned`.
//
// Why this earns a check script: until sender-chosen @mentions existed, every
// `p` tag on a boost note came from parseFeedNpubs, and `check:npub` pinned it
// end to end. There are now TWO sources with different trust, and the risk line
// in CLAUDE.md — "a note `p`-tags a stranger under the site's identity,
// permanently" — is no longer backed by that script alone. This is the other
// half.
//
// Both failure directions are silent and land on somebody who did not ask:
//
//   - Over-tagging is the serious one. /api/nostr/site-sign is UNAUTHENTICATED
//     and signs under a NIP-05-verified identity, which is why it caps p tags
//     at 8 and calls them "the amplifier". If `selfSigned` stops being honored,
//     every signed-out boost can ring four strangers' phones from a verified
//     name, and nothing on screen looks different. An unvalidated pubkey is the
//     same failure one layer down: a `p` tag pointing at whoever the bytes
//     decode to, on an immutable kind:1, with no way to unsend.
//   - Under-tagging silently drops the artist the money went to, which is the
//     feature the feed-declared half exists for — hence the must-still-work
//     vectors below (feed npubs survive Anonymous, a sender's mention still
//     reaches the body when it cannot reach the tags).
//
// EVERY VECTOR IS A RECORDED CALL, NOT A BARE ASSERTION. `naive()` at the foot
// is the obvious wrong version — concatenate both lists, trust the input,
// ignore `selfSigned` — and the whole vector list is replayed against it,
// because a vector that passes the moment it is written has proved nothing.
// The exemptions are named one at a time with `{ alsoNaive: true }`: those are
// must-still-work inputs, where naive() being right is a property of the input
// rather than a hole in the suite.
//
// The pubkeys are real, well-known public keys (jack, fiatjaf), so the hex is
// independently checkable. Vectors were generated by the shipping code; if one
// fails, fix the code — never edit the vector to match.

import {
  noteMentionTags,
  MAX_FEED_NOTE_NPUBS,
  MAX_MENTION_NPUBS,
} from '../lib/nostr/mention-tags.ts';
import { importFreeProblems, explainImportFree } from './import-free.mjs';

let failures = 0;

/** Every recorded call, replayed against naive() below. */
const vectors = [];

function compare(label, actual, expected) {
  const a = JSON.stringify(actual);
  const e = JSON.stringify(expected);
  if (a === e) {
    console.log(`  ok    ${label}`);
    return;
  }
  failures += 1;
  console.error(`  FAIL  ${label}\n          expected ${e}\n          actual   ${a}`);
}

/** A noteMentionTags vector. `alsoNaive` marks a must-still-work input. */
function check(label, feed, chosen, selfSigned, expected, { alsoNaive = false } = {}) {
  compare(label, noteMentionTags(feed, chosen, selfSigned), expected);
  vectors.push({ label, args: [feed, chosen, selfSigned], alsoNaive });
}

function section(name) {
  console.log(`\n${name}`);
}

// Real, well-known keys. npub + hex are a matched pair in each case.
const JACK = {
  npub: 'npub1sg6plzptd64u62a878hep2kev88swjh3tw00gjsfl8f237lmu63q0uf63m',
  pubkey: '82341f882b6eabcd2ba7f1ef90aad961cf074af15b9ef44a09f9d2a8fbfbe6a2',
};
const FIATJAF = {
  npub: 'npub180cvv07tjdrrgpa0j7j7tmnyl2yr6yr7l8j4s3evf6u64th6gkwsyjh6w6',
  pubkey: '3bf0c63fcb93463407af97a5e5ee64fa883d107ef9e558472c4eb9aaaefa459d',
};
// Four more, so the caps can be exercised. Arbitrary 32-byte values; the npub
// is not derived from them, which does not matter here — this module validates
// SHAPE, and nip19 decoding is feed-xml.ts's job (pinned by check:npub).
const mk = (i) => ({
  npub: `npub1${'q'.repeat(58)}${i}`,
  pubkey: `${String(i).repeat(2)}${'0'.repeat(62)}`.slice(0, 64),
});
const A = mk(1), B = mk(2), C = mk(3), D = mk(4), E = mk(5);

const none = { tagged: [], inBody: [] };

// ---------------------------------------------------------------------------
section('A self-signed note tags both sources');
// ---------------------------------------------------------------------------
{
  check(
    'feed alone', [JACK], [], true,
    { tagged: [JACK], inBody: [JACK] },
    { alsoNaive: true },
  );
  check(
    'a sender mention joins the feed npub, feed first',
    [JACK], [FIATJAF], true,
    { tagged: [JACK, FIATJAF], inBody: [JACK, FIATJAF] },
    { alsoNaive: true },
  );
  check(
    'a mention with no feed npub is still tagged',
    [], [FIATJAF], true,
    { tagged: [FIATJAF], inBody: [FIATJAF] },
    { alsoNaive: true },
  );
}

// ---------------------------------------------------------------------------
section('...and a SITE-SIGNED note tags only what the feed declared');
// ---------------------------------------------------------------------------
{
  // The whole reason this module exists. /api/nostr/site-sign is unauthenticated
  // and publishes under a NIP-05-verified identity.
  check(
    'the sender mention loses its p tag',
    [JACK], [FIATJAF], false,
    { tagged: [JACK], inBody: [JACK, FIATJAF] },
  );
  // ...but the artist the money went to keeps theirs. An anonymous boost should
  // still reach them; Anonymous protects the SENDER.
  check(
    'the feed npub keeps its p tag',
    [JACK], [], false,
    { tagged: [JACK], inBody: [JACK] },
    { alsoNaive: true },
  );
  // The signed-out sender still SEES who they named. A name vanishing from the
  // note you just published reads as the feature being broken.
  check(
    'a mention with no feed npub reaches the body and nothing else',
    [], [FIATJAF], false,
    { tagged: [], inBody: [FIATJAF] },
  );
}

// ---------------------------------------------------------------------------
section('Nothing that is not a usable identity becomes a p tag');
// ---------------------------------------------------------------------------
{
  check('both empty', [], [], true, none, { alsoNaive: true });
  check('null lists', null, undefined, true, none, { alsoNaive: true });
  // Uppercase hex is not what the rest of the app compares against, so it would
  // read as a different person everywhere a Set of pubkeys is used.
  check('uppercase hex pubkey', [], [{ ...JACK, pubkey: JACK.pubkey.toUpperCase() }], true, none);
  check('63-char pubkey', [], [{ ...JACK, pubkey: JACK.pubkey.slice(0, -1) }], true, none);
  check('65-char pubkey', [], [{ ...JACK, pubkey: `${JACK.pubkey}a` }], true, none);
  check('non-hex pubkey', [], [{ ...JACK, pubkey: JACK.pubkey.replace('82', 'zz') }], true, none);
  check('empty pubkey', [], [{ npub: JACK.npub, pubkey: '' }], true, none);
  // An nprofile names a person PLUS relay hints; a note/nevent names a thing.
  // Neither is what a `p` tag holds, and all three decode without throwing.
  check('an nprofile in the npub slot', [], [{ npub: 'nprofile1abc', pubkey: JACK.pubkey }], true, none);
  check('a note id in the npub slot', [], [{ npub: 'note1abc', pubkey: JACK.pubkey }], true, none);
  check('missing npub', [], [{ pubkey: JACK.pubkey }], true, none);
  check('a null entry in the list', [], [null, JACK], true, { tagged: [JACK], inBody: [JACK] });
  // The same rule applies to the FEED side. It was validated upstream, but this
  // is the last function before the tag array.
  check('a junk feed entry', [{ npub: 'x', pubkey: 'y' }, JACK], [], true, { tagged: [JACK], inBody: [JACK] });
}

// ---------------------------------------------------------------------------
section('The same person is named once, however many ways they arrive');
// ---------------------------------------------------------------------------
{
  // A sender @mentioning the artist the feed already declared must not produce
  // two p tags — that is two notifications for one boost.
  check(
    'a mention duplicating a feed npub collapses',
    [JACK], [JACK], true,
    { tagged: [JACK], inBody: [JACK] },
  );
  check('a feed npub listed twice collapses', [JACK, JACK], [], true, { tagged: [JACK], inBody: [JACK] });
  check('a mention listed twice collapses', [], [FIATJAF, FIATJAF], true, { tagged: [FIATJAF], inBody: [FIATJAF] });
  // The dedupe must not eat the OTHER person.
  check(
    'a duplicate does not consume the next mention',
    [JACK], [JACK, FIATJAF], true,
    { tagged: [JACK, FIATJAF], inBody: [JACK, FIATJAF] },
  );
}

// ---------------------------------------------------------------------------
section('Each source has its own cap, and the feed keeps its places');
// ---------------------------------------------------------------------------
{
  // The caps truncate, so ORDER is what decides who is dropped. A compilation
  // naming five artists must not lose one to the sender's @mention.
  check(
    'a fifth feed npub is dropped',
    [A, B, C, D, E], [], true,
    { tagged: [A, B, C, D], inBody: [A, B, C, D] },
  );
  check(
    'a fifth mention is dropped',
    [], [A, B, C, D, E], true,
    { tagged: [A, B, C, D], inBody: [A, B, C, D] },
  );
  // Four and four: exactly the site-sign route's MAX_P_TAGS, and only reachable
  // on the path that route never sees. If this number ever exceeds 8, a
  // self-signed note is fine and a site-signed one starts being REJECTED.
  check(
    'four of each is the ceiling, and it is 8',
    [A, B, C, D], [JACK, FIATJAF, E, { ...A, pubkey: `9${A.pubkey.slice(1)}` }], true,
    {
      tagged: [A, B, C, D, JACK, FIATJAF, E, { ...A, pubkey: `9${A.pubkey.slice(1)}` }],
      inBody: [A, B, C, D, JACK, FIATJAF, E, { ...A, pubkey: `9${A.pubkey.slice(1)}` }],
    },
    // naive() gets this right: nothing is dropped, so concatenation happens to
    // agree. That is a property of the input, and the ceiling is worth pinning
    // anyway — if it ever exceeds 8, a site-signed note starts being REJECTED.
    { alsoNaive: true },
  );
  // The caps are per-source, not shared: a full feed list must not starve the
  // sender's mentions, and a full mention list must not starve the feed's.
  check(
    'a full feed list still leaves room for mentions',
    [A, B, C, D], [JACK], true,
    { tagged: [A, B, C, D, JACK], inBody: [A, B, C, D, JACK] },
    // Also within naive()'s reach for the same reason. It pins that the caps
    // are PER SOURCE, which is what stops a compilation's artists starving the
    // sender's mentions.
    { alsoNaive: true },
  );
}

// ---------------------------------------------------------------------------
section('The caps are the numbers this module says they are');
// ---------------------------------------------------------------------------
{
  compare('MAX_FEED_NOTE_NPUBS', MAX_FEED_NOTE_NPUBS, 4);
  compare('MAX_MENTION_NPUBS', MAX_MENTION_NPUBS, 4);
  // The one that must hold against app/api/nostr/site-sign/route.ts.
  compare('their sum does not exceed MAX_P_TAGS', MAX_FEED_NOTE_NPUBS + MAX_MENTION_NPUBS <= 8, true);
}

// ---------------------------------------------------------------------------
console.log('\nEvery vector is replayed against the obvious wrong version');
// ---------------------------------------------------------------------------
{
  /**
   * The version somebody writes when the rule looks like a formality: trust
   * whatever is handed over, concatenate, and treat `selfSigned` as a display
   * concern. It gets the ordinary self-signed cases right, which is exactly why
   * the gate is easy to lose.
   */
  const naive = (feed, chosen) => {
    const all = [...(feed ?? []), ...(chosen ?? [])];
    return { tagged: all, inBody: all };
  };

  const call = (impl, v) => {
    try {
      return JSON.stringify(impl === 'real' ? noteMentionTags(...v.args) : naive(...v.args));
      // A wrong implementation is allowed to throw where the real one returns.
      // That still counts as differing — it is the loudest way to be wrong.
    } catch (e) {
      return `threw ${(e && e.message) || e}`;
    }
  };

  let exempt = 0;
  for (const v of vectors) {
    const differs = call('real', v) !== call('naive', v);
    if (v.alsoNaive) {
      exempt += 1;
      console.log(`  ok    "${v.label}" is must-still-work — naive() may get it right`);
      continue;
    }
    if (differs) {
      console.log(`  ok    naive() gets "${v.label}" wrong`);
      continue;
    }
    failures += 1;
    console.error(`  FAIL  "${v.label}" passes against naive() too — the vector proves nothing.`);
    console.error('          Either it is a must-still-work input (mark it { alsoNaive: true })');
    console.error('          or it does not exercise anything the real module adds.');
  }
  console.log(`  ${vectors.length} vector(s) replayed, ${exempt} exempt as must-still-work`);
}

// ---------------------------------------------------------------------------
console.log('\nmention-tags.ts stays loadable under plain Node');
// ---------------------------------------------------------------------------
{
  // The arrangement this whole script depends on: it imports the REAL module,
  // so the module must keep resolving under `node --experimental-strip-types`.
  // See scripts/import-free.mjs for why a type-only relative import counts.
  const problems = importFreeProblems('lib/nostr/mention-tags.ts');
  if (problems.length) { explainImportFree('lib/nostr/mention-tags.ts', problems); failures += problems.length; }
  else console.log('  ok    lib/nostr/mention-tags.ts has no imports that plain Node cannot resolve');
}

if (failures) {
  console.error(`\n${failures} mention-tag check(s) FAILED.`);
  process.exit(1);
}
console.log('\nAll mention-tag checks passed.');
